class LaunchStatus(StrEnum):
    """Статус решения о запуске."""

    GO = "go"
    NO_GO = "no_go"
    CAUTION = "caution"


class LaunchVerdict(BaseModel):
    """Вердикт о возможности запуска."""

    status: LaunchStatus
    reasons: list[str] = Field(default_factory=list, description="Причины решения")
    checked_at: datetime = Field(default_factory=datetime.utcnow)


class LaunchWindow(BaseModel):
    """Временное окно, подходящее для запуска."""

    start: datetime
    end: datetime
